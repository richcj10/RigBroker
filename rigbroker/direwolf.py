"""Direwolf configuration owned by the broker.

Three instances are rendered from one set of settings, one per consumer service:

* ``aprs``    - APRS on the air: KISS for the broker, optional beacon / digipeater / iGate.
* ``aprs-rx`` - quiet hours: receive + iGate RX only. **No PTT line at all**, so this
  instance physically cannot key the radio.
* ``pkt``     - plain 1200-baud packet modem for Pat (AGW only, KISS off, no beacons).

PTT always goes through rigctld (``PTT RIG 2 localhost:<port>``): rigctld owns the
Digirig serial port. Every value is validated (see config.DirewolfSettings) before it is
written, so nothing user-supplied can inject extra config lines.
"""

from __future__ import annotations

import contextlib
import json
import os
import shutil
import tempfile
import time
from pathlib import Path
from typing import Any, Literal

from pydantic import ValidationError

from .config import DirewolfConfig, DirewolfSettings

Instance = Literal["aprs", "aprs-rx", "pkt"]
INSTANCES: tuple[Instance, ...] = ("aprs", "aprs-rx", "pkt")
SERVICE_PREFIX = "direwolf@"


class SettingsError(ValueError):
    """Rejected settings change (message is user-readable)."""


def aprs_passcode(callsign: str) -> int:
    """APRS-IS passcode for a callsign (the standard, public algorithm; SSID ignored)."""
    base = callsign.split("-")[0].upper()
    h = 0x73E2
    for i in range(0, len(base), 2):
        h ^= ord(base[i]) << 8
        if i + 1 < len(base):
            h ^= ord(base[i + 1])
    return h & 0x7FFF


def _dm(value: float, pos: str, neg: str, deg_width: int) -> str:
    """Decimal degrees -> Direwolf's DD^MM.mmH form."""
    hemi = pos if value >= 0 else neg
    v = abs(value)
    deg = int(v)
    minutes = (v - deg) * 60
    if round(minutes, 2) >= 60:
        deg, minutes = deg + 1, 0.0
    return f"{deg:0{deg_width}d}^{minutes:05.2f}{hemi}"


def render(s: DirewolfSettings, callsign: str, instance: Instance, *,
           mask_secrets: bool = False) -> str:
    """Direwolf config text for one instance."""
    lines = [
        f"# Direwolf config for direwolf@{instance} - GENERATED BY RIGBROKER.",
        "# Edit the settings in the RigBroker UI; manual changes here are overwritten.",
        f"# Written {time.strftime('%Y-%m-%d %H:%M:%S')}",
        "",
        f"ADEVICE {s.adevice}",
        f"ARATE {s.arate}",
        "ACHANNELS 1",
        "CHANNEL 0",
        f"MYCALL {callsign}",
        "MODEM 1200",
    ]
    if instance == "aprs-rx":
        lines.append("# no PTT: quiet hours, this instance cannot transmit")
    else:
        lines.append(f"PTT RIG 2 localhost:{s.rigctld_port}")
        lines += [f"TXDELAY {s.txdelay}", f"TXTAIL {s.txtail}"]
    if instance == "pkt":
        # AGW for local clients; KISS on its own port for Winlink Express over the LAN
        # (deliberately not the APRS kiss_port, so the broker's APRS link never attaches)
        lines += [f"AGWPORT {s.agw_port}", f"KISSPORT {s.pkt_kiss_port}"]
        return "\n".join(lines) + "\n"

    lines += ["AGWPORT 0", f"KISSPORT {s.kiss_port}"]
    if instance == "aprs":
        if s.beacon and s.lat is not None and s.lon is not None:
            via = f" via={','.join(s.beacon_path)}" if s.beacon_path else ""
            comment = f' comment="{s.comment}"' if s.comment else ""
            lines.append(
                f'PBEACON delay=1 every={s.beacon_every_min} symbol="{s.symbol}" '
                f"lat={_dm(s.lat, 'N', 'S', 2)} long={_dm(s.lon, 'E', 'W', 3)}{via}{comment}")
        if s.digipeater == "fill-in":
            lines.append("DIGIPEAT 0 0 ^WIDE1-1$ ^WIDE1-1$")
        elif s.digipeater == "wide":
            lines.append("DIGIPEAT 0 0 ^WIDE[3-7]-[1-7]$|^TEST$ ^WIDE[12]-[12]$ TRACE")
    if s.igate:
        code = s.passcode if s.passcode is not None else aprs_passcode(callsign)
        lines += [f"IGSERVER {s.igate_server}",
                  f"IGLOGIN {callsign} {'*****' if mask_secrets else code}"]
        if instance == "aprs" and s.igate_tx:
            lines += ["IGTXVIA 0 WIDE1-1,WIDE2-1", "IGTXLIMIT 6 10"]
    return "\n".join(lines) + "\n"


class DirewolfManager:
    """Holds the current settings (config defaults + UI overlay) and writes config files."""

    def __init__(self, cfg: DirewolfConfig, callsign: str) -> None:
        self.cfg = cfg
        self.callsign = callsign
        self.conf_dir = Path(os.path.expanduser(cfg.conf_dir))
        self._settings_path = (Path(os.path.expanduser(cfg.settings_file))
                               if cfg.settings_file else None)
        self.settings = cfg.defaults
        self.last_written: float | None = None
        if self._settings_path and self._settings_path.exists():
            try:
                self.settings = DirewolfSettings.model_validate(
                    {**cfg.defaults.model_dump(), **json.loads(self._settings_path.read_text())})
            except (ValueError, ValidationError):
                bad = self._settings_path.with_suffix(f".invalid-{int(time.time())}")
                self._settings_path.replace(bad)

    def update(self, changes: dict[str, Any]) -> DirewolfSettings:
        """Validate and save a partial update. Raises SettingsError."""
        merged = {**self.settings.model_dump(), **changes}
        try:
            new = DirewolfSettings.model_validate(merged)
        except ValidationError as exc:
            msgs = "; ".join(f"{'.'.join(str(p) for p in e['loc']) or 'settings'}: {e['msg']}"
                             for e in exc.errors())
            raise SettingsError(msgs) from None
        self.settings = new
        if self._settings_path:
            self._atomic_write(self._settings_path, json.dumps(new.model_dump(), indent=1),
                               0o600)
        return new

    def public_settings(self) -> dict[str, Any]:
        d = self.settings.model_dump()
        d["passcode"] = None if self.settings.passcode is None else "set"
        return d

    def render_all(self, *, mask_secrets: bool = False) -> dict[Instance, str]:
        return {i: render(self.settings, self.callsign, i, mask_secrets=mask_secrets)
                for i in INSTANCES}

    def path(self, instance: Instance) -> Path:
        return self.conf_dir / f"{instance}.conf"

    def write(self) -> list[Path]:
        """Write all instance configs (0600: they may contain the iGate passcode)."""
        paths = []
        for inst, text in self.render_all().items():
            p = self.path(inst)
            self._atomic_write(p, text, 0o600)
            paths.append(p)
        self.last_written = time.time()
        return paths

    @staticmethod
    def installed() -> str | None:
        return shutil.which("direwolf")

    @staticmethod
    def _atomic_write(path: Path, text: str, mode: int) -> None:
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".tmp-")
        with contextlib.suppress(AttributeError, OSError):  # no fchmod on Windows dev boxes
            os.fchmod(fd, mode)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, path)
